test "a Stable file new at this release counts as additions only" {
    var pairs = unchanged();
    pairs[indexOf("docs/generated-shape.txt")] = .{ .old = null, .new = base_stable };
    pairs[indexOf("docs/generated-shape-experimental.txt")] = .{ .old = null, .new = base_experimental };
    const list = try drifts(pairs);
    defer freeDrifts(&list);
    try testing.expect(list[indexOf("docs/generated-shape.txt")].absent_at_prev);
    try testing.expectEqual(@as(usize, 3), list[indexOf("docs/generated-shape.txt")].diff.added);

    const minor = try drift.evaluate(gpa, .minor, &list, drift.readChangelog(empty_changelog, "0.20.0"));
    defer gpa.free(minor);
    try testing.expectEqual(@as(usize, 0), minor.len);

    const patch = try drift.evaluate(gpa, .patch, &list, drift.readChangelog(empty_changelog, "0.19.2"));
    defer gpa.free(patch);
    try testing.expectEqual(@as(usize, 1), countKind(patch, .patch_with_drift));
}

test "no drift under a patch bump is green" {
    const list = try drifts(unchanged());
    defer freeDrifts(&list);
    const findings = try drift.evaluate(gpa, .patch, &list, drift.readChangelog(empty_changelog, "0.19.2"));
    defer gpa.free(findings);
    try testing.expectEqual(@as(usize, 0), findings.len);
}

test "an unbumped version with drift is a note, not a failure" {
    var pairs = unchanged();
    pairs[indexOf("docs/api-snapshot-experimental.txt")].new = base_experimental ++ "lib.z: fn () void\n";
    const list = try drifts(pairs);
    defer freeDrifts(&list);
    const findings = try drift.evaluate(gpa, .none, &list, drift.readChangelog(empty_changelog, null));
    defer gpa.free(findings);
    try testing.expectEqual(@as(usize, 1), countKind(findings, .bump_pending));
    try testing.expectEqual(drift.Severity.note, drift.severity(.bump_pending));
    try testing.expectEqual(@as(usize, 0), failures(findings));
}

