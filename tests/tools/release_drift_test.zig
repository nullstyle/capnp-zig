// evaluate: the plan's four ablations, on fixture text.
// ---------------------------------------------------------------------------

test "plan ablation 1: editing one Stable line without a Breaking entry is red" {
    var pairs = unchanged();
    pairs[indexOf("docs/generated-shape.txt")].new = header ++ "lib.a: fn () void\nlib.b: fn (u64) error{Bad}!void\nlib.c: struct\n";
    const list = try drifts(pairs);
    defer freeDrifts(&list);
    const findings = try drift.evaluate(gpa, .minor, &list, drift.readChangelog(empty_changelog, "0.20.0"));
    defer gpa.free(findings);
    try testing.expectEqual(@as(usize, 1), countKind(findings, .stable_removal_without_breaking));
    try testing.expectEqualStrings("docs/generated-shape.txt", findings[0].path.?);
    try testing.expectEqual(@as(usize, 1), failures(findings));
}

test "plan ablation 2: adding one line only, with a minor bump, is green" {
    var pairs = unchanged();
    pairs[indexOf("docs/generated-shape.txt")].new = base_stable ++ "lib.d: fn () void\n";
    const list = try drifts(pairs);
    defer freeDrifts(&list);
    const findings = try drift.evaluate(gpa, .minor, &list, drift.readChangelog(empty_changelog, "0.20.0"));
    defer gpa.free(findings);
    try testing.expectEqual(@as(usize, 0), failures(findings));
    try testing.expectEqual(@as(usize, 0), findings.len);
}

test "plan ablation 3: a patch bump with an added line is red" {
    var pairs = unchanged();
    pairs[indexOf("docs/api-snapshot.txt")].new = base_stable ++ "lib.d: fn () void\n";
    const list = try drifts(pairs);
    defer freeDrifts(&list);
