test "the hook reads the five snapshot files, two of them Stable" {
    try testing.expectEqual(@as(usize, 5), drift.snapshots.len);
    const expected = [_]struct { []const u8, drift.Tier }{
        .{ "docs/api-snapshot.txt", .stable },
        .{ "docs/generated-shape.txt", .stable },
        .{ "docs/api-snapshot-experimental.txt", .experimental },
        .{ "docs/api-snapshot-experimental-quic.txt", .experimental },
        .{ "docs/generated-shape-experimental.txt", .experimental },
    };
    for (expected) |e| {
        try testing.expectEqual(e[1], drift.snapshots[indexOf(e[0])].tier);
    }
}

// ---------------------------------------------------------------------------
// diffLines.
// ---------------------------------------------------------------------------

test "diffLines: identical text has no drift" {
    const d = try drift.diffLines(gpa, base_stable, base_stable, 4);
    defer d.deinit(gpa);
    try testing.expectEqual(@as(usize, 0), d.added);
    try testing.expectEqual(@as(usize, 0), d.removed);
}

test "diffLines: a changed line is one removal and one addition" {
    const new = header ++ "lib.a: fn () void\nlib.b: fn (u32) error{Bad,Worse}!void\nlib.c: struct\n";
    const d = try drift.diffLines(gpa, base_stable, new, 4);
    defer d.deinit(gpa);
    try testing.expectEqual(@as(usize, 1), d.added);
    try testing.expectEqual(@as(usize, 1), d.removed);
    try testing.expectEqual(@as(usize, 1), d.removed_sample.len);
    try testing.expectEqualStrings("lib.b: fn (u32) error{Bad}!void", d.removed_sample[0]);
}

test "diffLines: header comments and blank lines are not surface" {
    const new = "# A rewritten header.\n\nlib.a: fn () void\n\nlib.b: fn (u32) error{Bad}!void\nlib.c: struct\n# trailer\n";
    const d = try drift.diffLines(gpa, base_stable, new, 4);
    defer d.deinit(gpa);
    try testing.expectEqual(@as(usize, 0), d.added);
    try testing.expectEqual(@as(usize, 0), d.removed);
}

test "diffLines: CRLF line ends match LF ones" {
    const new = "# STABLE public API snapshot\r\nlib.a: fn () void\r\nlib.b: fn (u32) error{Bad}!void\r\nlib.c: struct\r\n";
    const d = try drift.diffLines(gpa, base_stable, new, 4);
    defer d.deinit(gpa);
    try testing.expectEqual(@as(usize, 0), d.added);
    try testing.expectEqual(@as(usize, 0), d.removed);
}

test "diffLines: lines are a multiset and order does not matter" {
    const removed_dup = try drift.diffLines(gpa, "a\nb\nb\nc\n", "c\nb\na\n", 4);
    defer removed_dup.deinit(gpa);
    try testing.expectEqual(@as(usize, 0), removed_dup.added);
    try testing.expectEqual(@as(usize, 1), removed_dup.removed);

    // A duplicated line in the new text is an addition, too.
    const added_dup = try drift.diffLines(gpa, "a\nb\n", "b\na\nb\n", 4);
    defer added_dup.deinit(gpa);
    try testing.expectEqual(@as(usize, 1), added_dup.added);
    try testing.expectEqual(@as(usize, 0), added_dup.removed);
}

test "diffLines: a file new at this release is all additions" {
    const d = try drift.diffLines(gpa, "", base_stable, 4);
    defer d.deinit(gpa);
    try testing.expectEqual(@as(usize, 3), d.added);
    try testing.expectEqual(@as(usize, 0), d.removed);
}

test "diffLines: the removed sample keeps file order and stops at the limit" {
    const old = "r1\nkeep\nr2\nr3\n";
    const d = try drift.diffLines(gpa, old, "keep\n", 2);
    defer d.deinit(gpa);
    try testing.expectEqual(@as(usize, 3), d.removed);
    try testing.expectEqual(@as(usize, 2), d.removed_sample.len);
    try testing.expectEqualStrings("r1", d.removed_sample[0]);
    try testing.expectEqualStrings("r2", d.removed_sample[1]);
}

