//! Tests for tools/release_drift.zig, the release hook behind
//! `just check-release-drift`.
//!
//! The tool's git and file reads are glue; these tests drive its pure core:
//! the line diff, the bump classifier, the CHANGELOG reader and the rules
//! that turn drift into findings. The four "plan" tests replay the
//! ablations from docs/sprint-plan-2026-10-04.md item 3 on fixture text.

const std = @import("std");
const drift = @import("release-drift");
const testing = std.testing;

const gpa = testing.allocator;

fn version(text: []const u8) std.SemanticVersion {
    return std.SemanticVersion.parse(text) catch unreachable;
}

fn countKind(findings: []const drift.Finding, kind: drift.Kind) usize {
    var n: usize = 0;
    for (findings) |f| {
        if (f.kind == kind) n += 1;
    }
    return n;
}

fn failures(findings: []const drift.Finding) usize {
    var n: usize = 0;
    for (findings) |f| {
        if (drift.severity(f.kind) == .fail) n += 1;
    }
    return n;
}

/// One drift entry per snapshot file, from (old, new) text pairs. A null
/// old text means the file did not exist at the previous release.
const Pair = struct { old: ?[]const u8, new: []const u8 };

fn drifts(pairs: [drift.snapshots.len]Pair) ![drift.snapshots.len]drift.FileDrift {
    var out: [drift.snapshots.len]drift.FileDrift = undefined;
    for (drift.snapshots, pairs, 0..) |snapshot, pair, i| {
        out[i] = .{
            .path = snapshot.path,
            .tier = snapshot.tier,
            .absent_at_prev = pair.old == null,
            .diff = try drift.diffLines(gpa, pair.old orelse "", pair.new, 4),
        };
    }
    return out;
}

fn freeDrifts(list: []const drift.FileDrift) void {
    for (list) |d| d.diff.deinit(gpa);
}

const header = "# STABLE public API snapshot\n# Generated by a tool.\n";
const base_stable = header ++ "lib.a: fn () void\nlib.b: fn (u32) error{Bad}!void\nlib.c: struct\n";
const base_experimental = "# EXPERIMENTAL\nlib.x: fn () void\nlib.y: field u8\n";
const empty_changelog = "# Changelog\n\n## [Unreleased]\n\n## [0.19.1] - 2026-10-04\n\n### Security\n\n- A fix.\n";

/// The five files unchanged.
fn unchanged() [drift.snapshots.len]Pair {
    var out: [drift.snapshots.len]Pair = undefined;
    for (drift.snapshots, 0..) |snapshot, i| {
        const text = if (snapshot.tier == .stable) base_stable else base_experimental;
        out[i] = .{ .old = text, .new = text };
    }
    return out;
}

fn indexOf(path: []const u8) usize {
    for (drift.snapshots, 0..) |snapshot, i| {
        if (std.mem.eql(u8, snapshot.path, path)) return i;
    }
    unreachable;
}

