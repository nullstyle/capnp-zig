test "classifyBump: none, patch, minor, major" {
    try testing.expectEqual(drift.Bump.none, try drift.classifyBump(version("0.19.1"), version("0.19.1")));
    try testing.expectEqual(drift.Bump.patch, try drift.classifyBump(version("0.19.1"), version("0.19.2")));
    try testing.expectEqual(drift.Bump.minor, try drift.classifyBump(version("0.19.1"), version("0.20.0")));
    // A minor bump that does not reset the patch is still a minor bump.
    try testing.expectEqual(drift.Bump.minor, try drift.classifyBump(version("0.19.1"), version("0.20.3")));
    try testing.expectEqual(drift.Bump.major, try drift.classifyBump(version("0.19.1"), version("1.0.0")));
}

test "classifyBump: a version that goes backwards is an error" {
    try testing.expectError(error.VersionWentBackwards, drift.classifyBump(version("0.19.1"), version("0.19.0")));
    try testing.expectError(error.VersionWentBackwards, drift.classifyBump(version("0.19.1"), version("0.18.9")));
    try testing.expectError(error.VersionWentBackwards, drift.classifyBump(version("1.0.0"), version("0.99.0")));
}

test "zonVersion reads the manifest's .version" {
    const zon =
        \\.{
        \\    .name = .capnpc_zig,
        \\    .version = "0.19.1",
        \\    .minimum_zig_version = "0.17.0",
        \\}
    ;
    try testing.expectEqualStrings("0.19.1", drift.zonVersion(zon).?);
    try testing.expectEqual(@as(?[]const u8, null), drift.zonVersion(".{ .name = .x }"));
}

