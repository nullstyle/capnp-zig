test "each Stable file is checked on its own" {
    var pairs = unchanged();
    pairs[indexOf("docs/api-snapshot.txt")].new = header ++ "lib.a: fn () void\n";
    pairs[indexOf("docs/generated-shape.txt")].new = header ++ "lib.a: fn () void\n";
    const list = try drifts(pairs);
    defer freeDrifts(&list);
    const findings = try drift.evaluate(gpa, .minor, &list, drift.readChangelog(empty_changelog, null));
    defer gpa.free(findings);
    try testing.expectEqual(@as(usize, 2), countKind(findings, .stable_removal_without_breaking));
}

test "an Experimental removal without a Breaking (Experimental) entry warns, and does not fail" {
    var pairs = unchanged();
    pairs[indexOf("docs/generated-shape-experimental.txt")].new = "# EXPERIMENTAL\nlib.x: fn () void\n";
    const list = try drifts(pairs);
    defer freeDrifts(&list);
    const findings = try drift.evaluate(gpa, .minor, &list, drift.readChangelog(empty_changelog, "0.20.0"));
